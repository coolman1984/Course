# Builds desktop\dist\AI_Academy.exe: the course and the book PDF are gzip-compressed,
# AES-256-GCM encrypted with a fresh random key, embedded in the exe and only decrypted in memory.
# Usage (PowerShell 7):  pwsh desktop\build.ps1   [-SkipCourseBuild]
param([switch]$SkipCourseBuild)
$ErrorActionPreference = 'Stop'
$here = $PSScriptRoot
$root = Split-Path $here -Parent

if (-not $SkipCourseBuild) { node (Join-Path $root 'academy/build.mjs'); if ($LASTEXITCODE) { throw 'course build failed' } }

$payload = Join-Path $here 'obj/payload'
New-Item -ItemType Directory -Force $payload | Out-Null
Get-ChildItem $payload -Filter *.bin | Remove-Item -Force

$key = [byte[]]::new(32); [Security.Cryptography.RandomNumberGenerator]::Fill($key)

function Protect([string]$src, [string]$name) {
  $raw = [IO.File]::ReadAllBytes($src)
  $ms = [IO.MemoryStream]::new()
  $gz = [IO.Compression.GZipStream]::new($ms, [IO.Compression.CompressionLevel]::SmallestSize)
  $gz.Write($raw, 0, $raw.Length); $gz.Dispose()
  $plain = $ms.ToArray()
  $nonce = [byte[]]::new(12); [Security.Cryptography.RandomNumberGenerator]::Fill($nonce)
  $tag = [byte[]]::new(16); $cipher = [byte[]]::new($plain.Length)
  $aes = [Security.Cryptography.AesGcm]::new($key, 16)
  $aes.Encrypt($nonce, $plain, $cipher, $tag, [Text.Encoding]::UTF8.GetBytes($name)); $aes.Dispose()
  [IO.File]::WriteAllBytes((Join-Path $payload "$name.bin"), [byte[]]($nonce + $tag + $cipher))
  '{0,-12} {1,10:N0} -> {2,10:N0} bytes' -f $name, $raw.Length, ($cipher.Length + 28)
}

Protect (Join-Path $root 'AI_Academy.html') 'course'
$pdf = Join-Path $root 'AI_Essentials_Course_For_Modern_Workspace.pdf'
if (Test-Path $pdf) { Protect $pdf 'book' }
$tour = Join-Path $root 'AI_Academy_tour.mp4'   # played by the «▶ شاهد» button (TOUR in engine/core.js)
if (Test-Path $tour) { Protect $tour 'tour' }

# the key is stored split into two XOR halves so it never appears as one constant
$mask = [byte[]]::new(32); [Security.Cryptography.RandomNumberGenerator]::Fill($mask)
$mixed = for ($i = 0; $i -lt 32; $i++) { $key[$i] -bxor $mask[$i] }
$fmt = { param($b) ($b | ForEach-Object { '0x{0:X2}' -f $_ }) -join ',' }
@"
// generated by build.ps1 — do not commit
namespace AIAcademy;
static partial class Vault
{
    static readonly byte[] A = { $(& $fmt $mixed) };
    static readonly byte[] B = { $(& $fmt $mask) };
}
"@ | Set-Content (Join-Path $payload 'Key.g.cs') -Encoding utf8

$dist = Join-Path $here 'dist'
dotnet publish (Join-Path $here 'AIAcademy.csproj') -c Release -o $dist --nologo -v:q
if ($LASTEXITCODE) { throw 'dotnet publish failed' }
Get-ChildItem $dist -Exclude 'AI_Academy.exe' | Remove-Item -Recurse -Force
$exe = Get-Item (Join-Path $dist 'AI_Academy.exe')
'Built {0} ({1:N1} MB)' -f $exe.FullName, ($exe.Length / 1MB)
